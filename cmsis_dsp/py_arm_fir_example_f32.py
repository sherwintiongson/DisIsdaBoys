def test123():
    # sampling rate 2KHz, nyquist is 2KHz / 2 = 1KHz
    t = np.linspace(0, 1, 2001)

    # generate 5Hz sine wave sine(2*pi*f*t)
    sig_5Hz = np.sin(2 * np.pi * 5 * t)
    sig_50Hz = np.sin(2 * np.pi * 50 * t)
    sig_250Hz = np.sin(2 * np.pi * 250 * t)
    sig_combined = sig_5Hz + sig_250Hz + sig_50Hz

    # Instantiate and initialize filter
    firf32 = dsp.arm_fir_instance_f32()
    dsp.arm_fir_init_f32(firf32, NUM_TAPS, firCoeffs32, firStateF32)

    # Filter
    filtered_data = dsp.arm_fir_f32(firf32, sig_5Hz)
    print(filtered_data)

    plt.plot(filtered_data,label ='filtered_data')
    plt.xlabel('time')
    plt.title('Simple Chart')
    plt.legend()
    plt.show()





